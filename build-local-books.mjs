import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const sourceDirectory = path.resolve("texts");
const outputDirectory = path.join(sourceDirectory, "local");
const files = (await readdir(sourceDirectory))
  .filter((name) => /^pg\d+\.txt$/i.test(name))
  .sort((a, b) => Number(a.slice(2)) - Number(b.slice(2)));

await mkdir(outputDirectory, { recursive: true });

for (const filename of files) {
  const id = filename.match(/\d+/)[0];
  const text = await readFile(path.join(sourceDirectory, filename), "utf8");
  const encoded = JSON.stringify(text)
    .replaceAll("\u2028", "\\u2028")
    .replaceAll("\u2029", "\\u2029");
  const moduleText =
    "window.ATHENAEUM_LOCAL_TEXTS = window.ATHENAEUM_LOCAL_TEXTS || {};\n" +
    `window.ATHENAEUM_LOCAL_TEXTS[${JSON.stringify(id)}] = ${encoded};\n`;
  await writeFile(path.join(outputDirectory, `pg${id}.js`), moduleText, "utf8");
}

const cataloguePath = path.resolve("data/open-access-catalog.json");
const catalogueOutput = path.resolve("data/open-access-catalog.js");
const catalogue = JSON.parse(await readFile(cataloguePath, "utf8"));
const requiredSources = ["standard-ebooks", "wikisource", "internet-archive", "open-library", "doab-oapen", "librivox"];
const permittedLicences = new Set(["Public Domain", "CC0", "CC BY", "CC BY-SA"]);
const permittedRooms = new Set(["gothic", "inquiry", "chart", "drawing", "study", "garden", "contested", "returning", "quiet", "unread", "repository", "mainhall", "sorting"]);

for (const source of requiredSources) {
  if (!catalogue.sources?.[source]) throw new Error(`Missing open-access source: ${source}`);
}

const publishedBooks = [];
const seenIds = new Set();
for (const record of catalogue.books || []) {
  if (record.status !== "published") continue;
  for (const field of ["id", "title", "author", "category", "source", "sourceUrl", "licence", "licenceUrl", "room"]) {
    if (record[field] === undefined || record[field] === "") throw new Error(`Published open-access record ${record.id || "(unknown)"} is missing ${field}`);
  }
  if (!catalogue.sources[record.source]) throw new Error(`Unknown source ${record.source} on ${record.id}`);
  if (!Number.isInteger(record.id) || record.id < 900000 || seenIds.has(record.id)) throw new Error(`Open-access id ${record.id} must be a unique integer above 900000`);
  if (!permittedLicences.has(record.licence)) throw new Error(`Licence ${record.licence} is not approved for ${record.id}`);
  if (!permittedRooms.has(record.room)) throw new Error(`Unknown room ${record.room} on ${record.id}`);
  if (!record.textPath && !record.textUrls?.length) throw new Error(`Published record ${record.id} needs a local textPath or reviewed textUrls`);
  if (record.textPath && !record.textPath.startsWith("texts/open-access/")) throw new Error(`Local open-access text ${record.id} must live in texts/open-access/`);
  seenIds.add(record.id);
  publishedBooks.push(record);
}

for (const record of publishedBooks) {
  if (!record.textPath) continue;
  const text = await readFile(path.resolve(record.textPath), "utf8");
  const encoded = JSON.stringify(text)
    .replaceAll("\u2028", "\\u2028")
    .replaceAll("\u2029", "\\u2029");
  const moduleText =
    "window.ATHENAEUM_LOCAL_TEXTS = window.ATHENAEUM_LOCAL_TEXTS || {};\n" +
    `window.ATHENAEUM_LOCAL_TEXTS[${JSON.stringify(String(record.id))}] = ${encoded};\n`;
  await writeFile(path.join(outputDirectory, `pg${record.id}.js`), moduleText, "utf8");
}

console.log(`Prepared ${files.length + publishedBooks.filter(record => record.textPath).length} local book scripts in ${outputDirectory}`);

const catalogueScript =
  "/* Generated by build-local-books.mjs. Edit open-access-catalog.json, not this file. */\n" +
  `window.ATHENAEUM_OPEN_ACCESS_SOURCES = ${JSON.stringify(catalogue.sources, null, 2)};\n` +
  `window.ATHENAEUM_OPEN_ACCESS_BOOKS = ${JSON.stringify(publishedBooks, null, 2)};\n` +
  `window.ATHENAEUM_BOOK_ENRICHMENTS = ${JSON.stringify(catalogue.enrichments || {}, null, 2)};\n`;
await writeFile(catalogueOutput, catalogueScript, "utf8");
console.log(`Prepared ${publishedBooks.length} reviewed open-access records from ${requiredSources.length} source channels`);
